def setup_logger(log_level: int = logging.INFO) -> logging.Logger:
    """
    Sets up a standardized logger for the ingestion engine.
    """
    logger = logging.getLogger("CCTV_Ingestion")
    logger.setLevel(log_level)
    
    if not logger.handlers:
        handler = logging.StreamHandler(sys.stdout)
        formatter = logging.Formatter(
            '[%(asctime)s] [%(levelname)s] [%(name)s] %(message)s',
            datefmt='%Y-%m-%d %H:%M:%S'
        )
        handler.setFormatter(formatter)
        logger.addHandler(handler)
        
    return logger

logger = setup_logger()

# ==============================================================================
# In-Memory Event Store (Thread-Safe)
# ==============================================================================
class InMemoryEventStore:
    """
    A thread-safe in-memory database to store, retrieve, and filter
    validated store telemetry events.
    """
    def __init__(self) -> None:
        self._lock = threading.Lock()
        self._events: List[CCTVEventPayload] = []
        
        # Deduplication index set: (camera_id, track_id, timestamp, event_type)
        self._dedup_index: Set[Tuple[str, int, float, str]] = set()

    def add_event(self, event: CCTVEventPayload) -> bool:
        """
        Validates and adds an event if it is unique.
        Returns True if successfully added, False if duplicate.
        """
        # Generate unique event signature
        signature = (
            event.camera_id,
            event.track_id,
            round(event.timestamp, 2),  # Round to avoid float precision discrepancies
            event.event_type
        )
        
        with self._lock:
            if signature in self._dedup_index:
                return False
                
            self._events.append(event)
            self._dedup_index.add(signature)
            return True

    def get_all_events(self) -> List[CCTVEventPayload]:
        """
        Returns a copy of all registered events.
        """
        with self._lock:
            return list(self._events)

    def get_events_by_camera(self, camera_id: str) -> List[CCTVEventPayload]:
        """
        Filters events by camera source.
        """
        with self._lock:
            return [e for e in self._events if e.camera_id == camera_id]

    def get_events_by_track(self, track_id: int) -> List[CCTVEventPayload]:
        """
        Filters events by customer tracking ID.
        """
        with self._lock:
            return [e for e in self._events if e.track_id == track_id]

    def clear(self) -> None:
        """
        Clears all stored events and the deduplication index.
        """
        with self._lock:
            self._events.clear()
            self._dedup_index.clear()
            logger.info("In-memory event store cleared.")

    @property
    def count(self) -> int:
        """
        Returns total number of events in memory.
        """
        with self._lock:
            return len(self._events)


# Global Singleton Instance for API & Dashboard usage
store = InMemoryEventStore()

